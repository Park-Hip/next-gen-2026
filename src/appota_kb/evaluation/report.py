"""Generate the test report from a run, with the review sheet and Hiep's review skeleton (review.py).

Run by hand: `python -m appota_kb.evaluation.report results/<run_id>.jsonl`. It reads the results
file offline, scores it, prints the gates, writes the review sheet, creates the review YAML
once (never overwriting Hiep's entries), and writes docs/mission2/test_report.md only when
every row of data/test_cases.yaml has an ok or leak record.

The report is deterministic: it holds no generation timestamp, only what the records say.
"""
import json
import sys
from pathlib import Path

from appota_kb.core.config import load_config
from appota_kb.core.paths import RESULTS, ROOT
from appota_kb.evaluation.review import (
    CARD_LABEL,
    KIND_LABEL,
    build_review_sheet,
    lesson_of,
    load_reviews,
    review_skeleton,
)
from appota_kb.evaluation.score import CHECKS, Gate, RowScore, gates, load_run, score_all, verdicts
from appota_kb.integrations.data_files import cases_sha256, load_org, load_personas, load_test_cases

REPORT_REL = Path("docs") / "mission2" / "test_report.md"
REPORT_PATH = ROOT / REPORT_REL

# Each limitation row links the issue that keeps it open (ADR 0006).
LIMITATION_ISSUES = {15: "#24", 16: "#51", 17: "#52", 19: "#74"}


def _cell(text) -> str:
    """Escape a markdown table cell: pipes and newlines."""
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def _write_lf(path: Path, text: str) -> None:
    """Write `text` with LF endings on every OS.

    Path.write_text opens in default text mode, which Python on Windows uses to
    translate ``\n`` to CRLF; newline="\\n" keeps the written file LF-only so git's
    `eol=lf` normalisation does not warn.
    """
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def failures(score: RowScore) -> list[str]:
    out = [name for name in CHECKS if name in score.checks and score.checks[name] is False]
    for flag, name in (
        (score.rules_wrong, "rules"),
        (score.leak, "leak"),
        (score.unsafe, "unsafe"),
        (score.over_cautious, "over-cautious"),
    ):
        if flag:
            out.append(name)
    return out


def _actual(score: RowScore) -> str:
    """The card the employee saw, in one line; the basis of "Kết quả thực tế"."""
    if score.record is None:
        return "không trả lời được (chỉ có lỗi)"
    card = score.record.get("card")
    if not card:
        return "không có thẻ (rò rỉ giới hạn)"
    kind = card["kind"]
    label = CARD_LABEL[kind]
    if kind == "answer":
        detail = card.get("answer_text") or ""
    elif kind == "conflict":
        pairs = [" và ".join(pair) for pair in card.get("conflicts", []) or []]
        detail = "mâu thuẫn giữa " + "; ".join(pairs)
    else:
        detail = card.get("reason") or ""
    text = f"{label}: {detail}" if detail else label
    failed = failures(score)
    if failed:
        text = text.rstrip(".") + ". Không đạt ở: " + ", ".join(failed)
    return text


def _started(records: list[dict]) -> str:
    return records[0]["started_at"] if records else "(no records)"


def build_report(
    run_id: str,
    results_rel: str,
    records: list[dict],
    rows: list[dict],
    scores: list[RowScore],
    reviews: dict,
    settings,
    personas,
) -> str:
    """The full report text, deterministic for the same inputs."""
    first = records[0] if records else {}
    gated = [s for s in scores if s.row["kind"] != "limitation" and s.record is not None]
    n = len(gated)
    allowed = int(settings.over_cautious_max_share * n)
    gate_list = gates(scores, reviews, settings, personas)
    marks = verdicts(scores, reviews)
    missing = [s.row["id"] for s in scores if s.record is None]

    out: list[str] = []
    out.append("# Test report (Mission 2)")
    out.append("")
    out.append(f"Generated by `python -m appota_kb.evaluation.report` from `{results_rel}`; do not edit by hand.")
    out.append('All data is simulated ("giả lập").')
    out.append("")

    out.append("## The run")
    out.append("")
    out.append(f"- Run id: `{run_id}`")
    out.append(f"- Started: {_started(records)}")
    commit = first.get("commit", "?")
    out.append(f"- Commit: `{commit}`" + (" (working tree was not clean)" if first.get("dirty") else ""))
    out.append(
        f"- Model: {first.get('model', '?')}, thinking level {first.get('thinking_level', '?')}; "
        f"embeddings {first.get('embedding_model', '?')}, top k {first.get('top_k', '?')}"
    )
    out.append(f"- Records: {len(records)} (one per row asked; a resumed run keeps its earlier error records)")
    out.append(f"- Test file rows: {len(rows)} in `data/test_cases.yaml`")
    out.append(
        "- Each case ran once, in its main wording (`questions[0]`); run-to-run variance and "
        "paraphrased questions are not measured (ADR 0006)."
    )
    out.append("- Context recall is not measured (ADR 0007).")
    if first.get("cases_sha256") and first["cases_sha256"] != cases_sha256():
        out.append(
            "- Warning: the test file changed since this run (`cases_sha256` differs); re-run "
            "the evaluation for a report on the current test file."
        )
    out.append("")

    out.append("## Gates")
    out.append("")
    if missing:
        out.append(
            "The run is incomplete: rows "
            + ", ".join(str(i) for i in missing)
            + " have no reply (only errors)."
        )
        out.append("")
    out.append(f"Gated rows: {n} (limitation rows are reported outside the gates).")
    out.append("Counts are shown as k of n (k failing rows of n).")
    out.append("")
    out.append("| Gate | Count | Threshold | Result |")
    out.append("|---|---|---|---|")
    for gate in gate_list:
        number = f"{gate.k} of {gate.n}"
        if gate.bound is not None and gate.k == 0:
            number += f" (95% upper bound {gate.bound * 100:.1f}%)"
        out.append(
            f"| {gate.name} | {number} | {_threshold(gate, allowed)} | {_gate_result(gate)} |"
        )
    out.append("")
    out.append(
        "Passing these gates on a small simulated set is the condition to open to employees, "
        "not proof."
    )
    unsafe_gate = next(g for g in gate_list if g.name == "Unsafe answers (card)")
    if unsafe_gate.k == 0 and n:
        out.append(
            f"With 0 unsafe answers in {n} gated rows, the true unsafe rate is below about "
            f"{unsafe_gate.bound * 100:.1f}% with 95% confidence."
        )
    out.append("")

    out.append("## The mix")
    out.append("")
    out.append("| Kind | Rows | Passed |")
    out.append("|---|---|---|")
    for kind in ("good", "hard", "limitation"):
        rows_of_kind = [s for s in scores if s.row["kind"] == kind]
        passed = sum(1 for s in rows_of_kind if marks[s.row["id"]] == "Đạt")
        out.append(f"| {KIND_LABEL[kind]} | {len(rows_of_kind)} | {passed} |")
    out.append("")

    out.append("## Cases")
    out.append("")
    out.append("| # | Tình huống | Kỳ vọng | Kết quả thực tế | Đạt/Chưa đạt | Điều học được |")
    out.append("|---|---|---|---|---|---|")
    for score in scores:
        row = score.row
        situation = (
            f"{KIND_LABEL[row['kind']]}; {row['persona']}, {row['as_of']}; "
            f"{row['questions'][0]}"
        )
        lesson = lesson_of(reviews.get(row["id"]))
        out.append(
            f"| {row['id']} | {_cell(situation)} | {_cell(row['expected_answer'])} | "
            f"{_cell(_actual(score))} | {_cell(marks[row['id']] or '-')} | {_cell(lesson)} |"
        )
    out.append("")

    caught = [s for s in scores if s.caught_by_step7]
    out.append("## Caught by step 7")
    out.append("")
    if caught:
        out.append(
            "Rows where the raw model reply was unsafe but the card the employee saw was not "
            "(examples for the video and for question 3)."
        )
        out.append("")
        for s in caught:
            out.append(f"- Row {s.row['id']} (`{s.row['questions'][0]}`)")
            for point in s.record.get("points") or []:
                out.append(f"  - {json.dumps(point, ensure_ascii=False)}")
    else:
        out.append("None.")
    out.append("")

    limitation = [s for s in scores if s.row["kind"] == "limitation"]
    out.append("## Limitation rows")
    out.append("")
    if limitation:
        out.append("Reported outside the gates; the issue stays open with the `limitation` label.")
        out.append("")
        for s in limitation:
            issue = LIMITATION_ISSUES.get(s.row["id"], "a limitation issue")
            out.append(
                f"- Row {s.row['id']}: {_cell(marks[s.row['id']] or '-')} (issue {issue}). "
                f"{_cell(s.row['expected_answer'])}"
            )
    else:
        out.append("None.")
    out.append("")

    errors = [(s.row["id"], s.errors) for s in scores if s.errors]
    out.append("## Errors during the run")
    out.append("")
    if errors:
        for row_id, errs in errors:
            resumed = " (later resumed)" if any(s.row["id"] == row_id and s.record is not None for s in scores) else ""
            for err in errs:
                out.append(
                    f"- Row {row_id}{resumed}: {err['error']['type']}: {_cell(err['error']['message'])}"
                )
    else:
        out.append("None.")
    out.append("")

    out.append("## Latency")
    out.append("")
    out.append("Wall time around each answer, including the rate limiter's wait; no target is set.")
    out.append("")
    for s in scores:
        if s.record is not None and s.record.get("latency_ms") is not None:
            out.append(f"- Row {s.row['id']}: {s.record['latency_ms']} ms")
    out.append("")

    out.append("## Reproduce")
    out.append("")
    out.append("```bash")
    out.append("uv run python -m appota_kb.evaluation.run")
    out.append(f"uv run python -m appota_kb.evaluation.report {results_rel}")
    out.append("```")
    out.append("")
    return "\n".join(out)


def _threshold(gate: Gate, allowed: int) -> str:
    if gate.reported:
        return "reported, not a gate"
    if gate.name == "Rules correct in every case":
        return "0, refusals identical"
    if gate.name == "Over-cautious":
        return f"at most {allowed}"
    if gate.name == "Faithfulness (Hiep's reading)":
        return "all marked yes"
    return "0"


def _gate_result(gate: Gate) -> str:
    if gate.reported:
        return "-"
    if gate.passed is None:
        return "[chờ Hiệp]"
    return "Đạt" if gate.passed else "Chưa đạt"


def _print_summary(rows: list[dict], scores: list[RowScore], gate_list: list[Gate], marks: dict) -> None:
    missing = [s.row["id"] for s in scores if s.record is None]
    print("Gates:")
    for gate in gate_list:
        number = f"{gate.k} of {gate.n}"
        if gate.bound is not None and gate.k == 0:
            number += f" (95% upper bound {gate.bound * 100:.1f}%)"
        print(f"  {gate.name}: {number} -> {_gate_result(gate)}")
    print("Rows:")
    for score in scores:
        print(f"  row {score.row['id']}: {marks[score.row['id']] or 'no reply'}")
    if missing:
        print(f"Incomplete: rows {', '.join(str(i) for i in missing)} have no reply; no report written.")


def main(argv: list[str]) -> int:
    # The summary is Vietnamese; a Windows console's cp1252 cannot encode it, so print
    # as UTF-8 instead of raising UnicodeEncodeError on the first non-ASCII character.
    if sys.stdout is not None and hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if len(argv) != 2:
        sys.stderr.write("usage: python -m appota_kb.evaluation.report results/<run_id>.jsonl\n")
        return 2
    results_path = Path(argv[1])
    if not results_path.exists():
        sys.stderr.write(f"{results_path}: not found\n")
        return 2
    run_id = results_path.stem

    config = load_config()
    rows = load_test_cases()
    personas = load_personas(load_org())
    records = load_run(results_path)
    scores = score_all(rows, records)
    reviews = load_reviews(RESULTS / f"{run_id}.review.yaml")
    gate_list = gates(scores, reviews, config.eval, personas)
    marks = verdicts(scores, reviews)

    _print_summary(rows, scores, gate_list, marks)

    review_md = RESULTS / f"{run_id}.review.md"
    _write_lf(review_md, build_review_sheet(run_id, scores, reviews))

    review_yaml = RESULTS / f"{run_id}.review.yaml"
    if not review_yaml.exists():
        _write_lf(review_yaml, review_skeleton(run_id, rows))

    results_rel = f"results/{run_id}.jsonl"
    complete = all(s.record is not None for s in scores)
    if complete:
        report = build_report(run_id, results_rel, records, rows, scores, reviews, config.eval, personas)
        _write_lf(REPORT_PATH, report)
        print("Report written to docs/mission2/test_report.md")
    else:
        missing = [s.row["id"] for s in scores if s.record is None]
        sys.stderr.write(
            f"No report written: rows {', '.join(str(i) for i in missing)} have no reply.\n"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))